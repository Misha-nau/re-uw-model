"""Regenerate docs/inputs.md from the Pydantic input model + the sample scenario.

Run from backend/:  python scripts/gen_input_docs.py
"""

from __future__ import annotations

import json
import typing

from pydantic import BaseModel

from re_uw.inputs import UnderwritingInputs
from re_uw.scenarios import PROJECT_ROOT, SCENARIOS_DIR, load_scenario

SECTION_TITLES = {
    "scenario": "Scenario",
    "analysis": "Analysis",
    "property": "Property",
    "components": "Space components (one row set per component: Office, Retail, ...)",
    "other_income": "Other income (list)",
    "acquisition": "Acquisition",
    "expenses": "Property-level expenses",
    "capex": "Capital expenditure",
    "debt": "Debt",
    "exit": "Exit",
    "fees": "Fund / manager fees",
    "waterfall": "Equity waterfall",
}


def _model_of(annotation) -> type[BaseModel] | None:
    """Return the BaseModel class inside an annotation like list[X] or X | None."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    for arg in typing.get_args(annotation):
        m = _model_of(arg)
        if m:
            return m
    return None


def _fmt(v) -> str:
    if isinstance(v, dict | list):
        return f"`{json.dumps(v)}`"
    if v is None:
        return "`null`"
    return f"`{v}`"


def _rows(model: type[BaseModel], sample, prefix: str):
    for name, field in model.model_fields.items():
        path = f"{prefix}.{name}" if prefix else name
        value = sample.get(name) if isinstance(sample, dict) else None
        sub = _model_of(field.annotation)
        if sub and isinstance(value, dict):
            yield from _rows(sub, value, path)
        elif sub and isinstance(value, list) and value and isinstance(value[0], dict):
            yield from _rows(sub, value[0], f"{path}[]")
        else:
            yield path, _fmt(value), (field.description or "").replace("|", "/")


def main() -> None:
    sample = load_scenario(SCENARIOS_DIR / "sample_sg_cbd_office_retail.json")
    data = sample.model_dump(mode="json")
    lines = [
        "# Input reference",
        "",
        "Generated by `backend/scripts/gen_input_docs.py` from `backend/re_uw/inputs.py`.",
        "Sample values come from `scenarios/sample_sg_cbd_office_retail.json` "
        "(for list sections, the first item is shown).",
        "",
        "Conventions: rates are decimals (0.05 = 5%); rents/opex are per sq ft per month; "
        "override dictionaries are keyed by year number (1 = first hold year).",
        "",
    ]
    for section, field in UnderwritingInputs.model_fields.items():
        if section == "schema_version":
            continue
        model = _model_of(field.annotation)
        lines += [f"## {SECTION_TITLES.get(section, section)}", "",
                  "| Field | Sample value | Description |", "|---|---|---|"]
        for path, val, desc in _rows(model, data[section] if not isinstance(data[section], list)
                                     else (data[section][0] if data[section] else {}),
                                     f"{section}[]" if isinstance(data[section], list)
                                     else section):
            lines.append(f"| `{path}` | {val} | {desc} |")
        lines.append("")
    out = PROJECT_ROOT / "docs" / "inputs.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
